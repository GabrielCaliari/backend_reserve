import { ApiPropertyOptional } from '@nestjs/swagger';
import { IsEnum, IsInt, IsOptional, Min } from 'class-validator';
import { Type } from 'class-transformer';
import { EAppointmentStatus } from '../../domain/entities/appointment.entity';

export class ListAppointmentsQueryDto {
  @ApiPropertyOptional({
    description: 'Page number',
    example: 1,
    minimum: 1,
  })
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(1)
  page?: number;

  @ApiPropertyOptional({
    description: 'Items per page',
    example: 10,
    minimum: 1,
  })
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(1)
  limit?: number;

  @ApiPropertyOptional({
    description: 'Filter by appointment status',
    enum: EAppointmentStatus,
    example: EAppointmentStatus.confirmed,
  })
  @IsOptional()
  @IsEnum(EAppointmentStatus)
  status?: EAppointmentStatus;
}
